"""KWin script sources (pure: no I/O).

Two static files exist. ``kwin/waddle-core.js`` (always loaded) reports Waddle's own window,
the outputs, the active window and the changes of the current target. ``kwin/waddle-cursor.js``
(loaded only while needed) streams the pointer position. The one-shot scripts are generated
here, one per request, with their arguments baked in because a running script cannot receive
calls (ARCHITECTURE §4.2): move one of Waddle's windows, report the pointer once, report the
window under a point.

Every script that looks at windows contains ``OWN_GUARD_JS`` verbatim, so "is this window
Waddle's?" has exactly one definition, and every script that describes a window contains
``WINDOW_PAYLOAD_JS`` verbatim, so the host parses one payload shape. Tests check the static
file against both.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Final

from waddle_core.identity import (
    APP_ID,
    DBUS_KWIN_INTERFACE,
    DBUS_PATH,
    DBUS_SERVICE,
    OVERLAY_WINDOW_TITLE,
    PENGUIN_WINDOW_TITLE,
)

CORE_SCRIPT_NAME: Final = "waddle-core.js"
CORE_PLUGIN_NAME: Final = "waddle-core"
CURSOR_SCRIPT_NAME: Final = "waddle-cursor.js"
CURSOR_PLUGIN_NAME: Final = "waddle-cursor"
OWN_TITLES: Final = (PENGUIN_WINDOW_TITLE, OVERLAY_WINDOW_TITLE)
# Logical pixels. Negative values are normal left of / above the primary output.
COORD_LIMIT: Final = 100_000

OWN_GUARD_JS: Final = f"""\
    // BEGIN OWN_GUARD (generated by waddle_desktop.kwin.scripts; do not edit by hand)
    var OWN_CLASS = {json.dumps(APP_ID.lower())};
    var OWN_TITLES = {json.dumps(list(OWN_TITLES))};
    function isOwnWindow(w) {{
        if (!w) {{
            return false;
        }}
        if (String(w.resourceClass || "").toLowerCase() !== OWN_CLASS) {{
            return false;
        }}
        return OWN_TITLES.indexOf(String(w.caption || "")) !== -1;
    }}
    // END OWN_GUARD
"""

# How a script describes a window to the host (``types.parse_window_info`` reads it). It only
# reads properties. Strings are cut here so one long title cannot push the payload over the
# host's size limit; the host cuts and cleans them again. ``isOwnClass`` is the class half of
# the guard above with any title, so Settings and Ask windows count as Waddle's too.
WINDOW_PAYLOAD_JS: Final = """\
    // BEGIN WINDOW_PAYLOAD (generated by waddle_desktop.kwin.scripts; do not edit by hand)
    function isOwnClass(w) {
        return !!w && String(w.resourceClass || "").toLowerCase() === OWN_CLASS;
    }
    function payloadText(value, limit) {
        return String(value === undefined || value === null ? "" : value).slice(0, limit);
    }
    function payloadNumber(value) {
        var n = Number(value);
        return isFinite(n) ? n : 0;
    }
    function payloadRect(g) {
        if (!g) {
            return { x: 0, y: 0, width: 0, height: 0 };
        }
        return {
            x: payloadNumber(g.x),
            y: payloadNumber(g.y),
            width: Math.max(0, payloadNumber(g.width)),
            height: Math.max(0, payloadNumber(g.height))
        };
    }
    function payloadId(w) {
        return String(w.internalId).replace(/[{}]/g, "");
    }
    // Spike S2.2 UNVERIFIED: KWin has no scriptable "is XWayland" property. This guesses from
    // the C++ class name that a QObject wrapper prints, and answers null when it cannot tell.
    function isXwayland(w) {
        try {
            var text = String(w);
            if (text.indexOf("X11Window") !== -1) {
                return true;
            }
            if (text.indexOf("XdgToplevelWindow") !== -1 ||
                    text.indexOf("XdgPopupWindow") !== -1 ||
                    text.indexOf("LayerShellV1Window") !== -1 ||
                    text.indexOf("InternalWindow") !== -1) {
                return false;
            }
        } catch (e) {
            // Unknown.
        }
        return null;
    }
    function describeWindow(w) {
        var output = w.output || null;
        var scale = output ? Number(output.devicePixelRatio) : 1;
        if (!(isFinite(scale) && scale > 0 && scale <= 16)) {
            scale = 1;
        }
        var pid = Number(w.pid);
        if (!(isFinite(pid) && pid >= 0 && Math.floor(pid) === pid)) {
            pid = 0;
        }
        return {
            uuid: payloadId(w),
            caption: payloadText(w.caption, 512),
            resourceClass: payloadText(w.resourceClass, 256),
            resourceName: payloadText(w.resourceName, 256),
            desktopFile: payloadText(w.desktopFileName, 256),
            pid: pid,
            frame: payloadRect(w.frameGeometry),
            client: payloadRect(w.clientGeometry || w.frameGeometry),
            output: payloadText(output ? output.name : "", 256),
            scale: scale,
            fullscreen: w.fullScreen === true,
            xwayland: isXwayland(w),
            own: isOwnClass(w)
        };
    }
    // END WINDOW_PAYLOAD
"""

_MOVE_TEMPLATE: Final = """\
// Waddle one-shot: move Waddle's own window. Generated; loaded, run once and unloaded.
(function () {
    "use strict";
@GUARD@
    var TITLE = @TITLE@;
    var X = @X@;
    var Y = @Y@;
    var ok = false;
    try {
        var windows = workspace.windowList();
        for (var i = 0; i < windows.length; i++) {
            var w = windows[i];
            if (isOwnWindow(w) && String(w.caption) === TITLE) {
                var g = w.frameGeometry;
                w.frameGeometry = { x: X, y: Y, width: g.width, height: g.height };
                ok = true;
                break;
            }
        }
    } catch (e) {
        ok = false;
    }
    callDBus(@SERVICE@, @PATH@, @INTERFACE@, "MoveDone",
        JSON.stringify({ title: TITLE, ok: ok, x: X, y: Y }));
})();
"""

_CURSOR_QUERY_TEMPLATE: Final = """\
// Waddle one-shot: report the pointer position once. Generated; loaded, run once and unloaded.
(function () {
    "use strict";
    try {
        var pos = workspace.cursorPos;
        var x = Number(pos.x);
        var y = Number(pos.y);
        if (isFinite(x) && isFinite(y)) {
            callDBus(@SERVICE@, @PATH@, @INTERFACE@, "Cursor", JSON.stringify({ x: x, y: y }));
        }
    } catch (e) {
        // No answer; the host times out.
    }
})();
"""

# Spike S8.2 UNVERIFIED: that workspace.stackingOrder is bottom-to-top and holds the windows
# of every virtual desktop, and that normalWindow / dialog / minimized / desktops read as
# assumed here. The script only reads; the host treats "no answer" as "no window".
_WINDOW_AT_TEMPLATE: Final = """\
// Waddle one-shot: which window is under a point. Generated; loaded, run once and unloaded.
// It reads window properties and changes nothing.
(function () {
    "use strict";
@GUARD@
@PAYLOAD@
    var X = @X@;
    var Y = @Y@;
    function onCurrentDesktop(w) {
        if (w.onAllDesktops === true) {
            return true;
        }
        var current = workspace.currentDesktop;
        var list = w.desktops;
        if (current === undefined || current === null || !list || !(list.length > 0)) {
            return true;
        }
        for (var i = 0; i < list.length; i++) {
            if (list[i] === current) {
                return true;
            }
            if (list[i] && current.id !== undefined && list[i].id === current.id) {
                return true;
            }
        }
        return false;
    }
    function candidate(w) {
        if (!w || isOwnClass(w) || isOwnWindow(w)) {
            return false;
        }
        if (w.normalWindow !== true && w.dialog !== true) {
            return false;
        }
        if (w.minimized === true || w.hidden === true || w.deleted === true) {
            return false;
        }
        if (!onCurrentDesktop(w)) {
            return false;
        }
        var g = w.frameGeometry;
        return !!g && X >= g.x && X < g.x + g.width && Y >= g.y && Y < g.y + g.height;
    }
    var found = null;
    var ok = false;
    try {
        var stack = workspace.stackingOrder;
        for (var i = stack.length - 1; i >= 0; i--) {
            if (candidate(stack[i])) {
                found = describeWindow(stack[i]);
                break;
            }
        }
        ok = true;
    } catch (e) {
        ok = false;
    }
    if (ok) {
        callDBus(@SERVICE@, @PATH@, @INTERFACE@, "WindowAt",
            JSON.stringify({ x: X, y: Y, window: found }));
    }
})();
"""


def core_script_path(base_dir: Path) -> Path:
    """Where ``waddle-core.js`` lives under ``base_dir`` (the directory that holds ``kwin/``)."""
    return base_dir / "kwin" / CORE_SCRIPT_NAME


def cursor_script_path(base_dir: Path) -> Path:
    """Where ``waddle-cursor.js`` lives under ``base_dir`` (the directory that holds ``kwin/``)."""
    return base_dir / "kwin" / CURSOR_SCRIPT_NAME


def _coordinate(name: str, value: int) -> int:
    if type(value) is not int:
        raise ValueError(f"{name} must be an int")
    if abs(value) > COORD_LIMIT:
        raise ValueError(f"{name} is out of range")
    return value


def _fill(template: str, values: dict[str, str]) -> str:
    """Fill the template markers. Only text built by this module is ever inserted: decimal
    ints, JSON string literals of Waddle's own constants, and the shared blocks."""
    fixed = {
        "@GUARD@": OWN_GUARD_JS.rstrip("\n"),
        "@PAYLOAD@": WINDOW_PAYLOAD_JS.rstrip("\n"),
        "@SERVICE@": json.dumps(DBUS_SERVICE),
        "@PATH@": json.dumps(DBUS_PATH),
        "@INTERFACE@": json.dumps(DBUS_KWIN_INTERFACE),
    }
    script = template
    for marker, text in {**fixed, **values}.items():
        script = script.replace(marker, text)
    return script


def render_move_script(title: str, x: int, y: int) -> str:
    """One-shot script moving Waddle's window titled ``title`` to logical (x, y), size kept.

    The first matching window is moved. Raises ``ValueError`` unless ``title`` is one of
    Waddle's two placed windows and the coordinates are ints within ``±COORD_LIMIT``.
    """
    if title not in OWN_TITLES:
        raise ValueError("title is not one of Waddle's placed windows")
    return _fill(
        _MOVE_TEMPLATE,
        {
            "@TITLE@": json.dumps(title),
            "@X@": str(_coordinate("x", x)),
            "@Y@": str(_coordinate("y", y)),
        },
    )


def render_cursor_query_script() -> str:
    """One-shot script reporting the pointer position once through ``Cursor``; no arguments."""
    return _fill(_CURSOR_QUERY_TEMPLATE, {})


def render_window_at_script(x: int, y: int) -> str:
    """One-shot script reporting the window under logical (x, y) through ``WindowAt``.

    The answer is ``{x, y, window}`` where ``window`` describes the topmost normal window or
    dialog on the current desktop that contains the point and is not Waddle's, or is null.
    The script answers nothing when it cannot read the stacking order. Raises ``ValueError``
    unless both coordinates are ints within ``±COORD_LIMIT``.
    """
    return _fill(
        _WINDOW_AT_TEMPLATE,
        {"@X@": str(_coordinate("x", x)), "@Y@": str(_coordinate("y", y))},
    )
