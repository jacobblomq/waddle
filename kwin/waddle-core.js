// Waddle core KWin script (persistent). Loaded at runtime by waddle-desktop, never installed.
//
// It reports to the host over callDBus, and it never assigns to any window property:
//   Hello / Outputs / OwnWindow  the Phase 1 reports: API check, output layout, the penguin.
//   Activated      the window that became active (and the active one at load), own or not.
//   TargetChanged  caption, geometry, fullscreen and output changes of the current target,
//                  which is the last activated window that is not one of Waddle's.
//   Popups         the target's transient popups, when that set changes.
//   DesktopChanged the virtual desktop was switched.
//
// Engine is QJSEngine: plain ES2015, no modules. Every optional API is typeof-guarded.
(function () {
    "use strict";

    var VERSION = 2;
    var SERVICE = "io.github.jacobblomq.Waddle";
    var PATH = "/io/github/jacobblomq/Waddle";
    var INTERFACE = "io.github.jacobblomq.Waddle.KWin";

    // BEGIN OWN_GUARD (generated by waddle_desktop.kwin.scripts; do not edit by hand)
    var OWN_CLASS = "io.github.jacobblomq.waddle";
    var OWN_TITLES = ["Waddle", "Waddle Highlight"];
    function isOwnWindow(w) {
        if (!w) {
            return false;
        }
        if (String(w.resourceClass || "").toLowerCase() !== OWN_CLASS) {
            return false;
        }
        return OWN_TITLES.indexOf(String(w.caption || "")) !== -1;
    }
    // END OWN_GUARD

    // BEGIN WINDOW_PAYLOAD (generated by waddle_desktop.kwin.scripts; do not edit by hand)
    function isOwnClass(w) {
        return !!w && String(w.resourceClass || "").toLowerCase() === OWN_CLASS;
    }
    function payloadText(value, limit) {
        return String(value === undefined || value === null ? "" : value).slice(0, limit);
    }
    function payloadNumber(value) {
        var n = Number(value);
        return isFinite(n) ? n : 0;
    }
    function payloadRect(g) {
        if (!g) {
            return { x: 0, y: 0, width: 0, height: 0 };
        }
        return {
            x: payloadNumber(g.x),
            y: payloadNumber(g.y),
            width: Math.max(0, payloadNumber(g.width)),
            height: Math.max(0, payloadNumber(g.height))
        };
    }
    function payloadId(w) {
        return String(w.internalId).replace(/[{}]/g, "");
    }
    // Spike S2.2 UNVERIFIED: KWin has no scriptable "is XWayland" property. This guesses from
    // the C++ class name that a QObject wrapper prints, and answers null when it cannot tell.
    function isXwayland(w) {
        try {
            var text = String(w);
            if (text.indexOf("X11Window") !== -1) {
                return true;
            }
            if (text.indexOf("XdgToplevelWindow") !== -1 ||
                    text.indexOf("XdgPopupWindow") !== -1 ||
                    text.indexOf("LayerShellV1Window") !== -1 ||
                    text.indexOf("InternalWindow") !== -1) {
                return false;
            }
        } catch (e) {
            // Unknown.
        }
        return null;
    }
    function describeWindow(w) {
        var output = w.output || null;
        var scale = output ? Number(output.devicePixelRatio) : 1;
        if (!(isFinite(scale) && scale > 0 && scale <= 16)) {
            scale = 1;
        }
        var pid = Number(w.pid);
        if (!(isFinite(pid) && pid >= 0 && Math.floor(pid) === pid)) {
            pid = 0;
        }
        return {
            uuid: payloadId(w),
            caption: payloadText(w.caption, 512),
            resourceClass: payloadText(w.resourceClass, 256),
            resourceName: payloadText(w.resourceName, 256),
            desktopFile: payloadText(w.desktopFileName, 256),
            pid: pid,
            frame: payloadRect(w.frameGeometry),
            client: payloadRect(w.clientGeometry || w.frameGeometry),
            output: payloadText(output ? output.name : "", 256),
            scale: scale,
            fullscreen: w.fullScreen === true,
            xwayland: isXwayland(w),
            own: isOwnClass(w)
        };
    }
    // END WINDOW_PAYLOAD

    var PENGUIN_TITLE = OWN_TITLES[0];
    var THROTTLE_MS = 100; // at most one TargetChanged per target in this time
    var MAX_POPUPS = 16;
    var MAX_POPUP_DEPTH = 8; // a submenu's parent is a menu whose parent is the target
    var TARGET_SIGNALS = ["captionChanged", "frameGeometryChanged", "clientGeometryChanged",
        "fullScreenChanged", "outputChanged"];
    var watched = {}; // window id -> true once its change signals are connected
    var lastSent = {}; // window id -> last OwnWindow payload, to coalesce
    // The current target, or null: {w, id, links: [{signal, fn}], lastText, cooling, pending,
    // popupLinks: {id: {signal, fn}}, popupsText}. Only ever one at a time.
    var target = null;

    function send(method, payload) {
        callDBus(SERVICE, PATH, INTERFACE, method, JSON.stringify(payload));
    }

    function canConnect(signal) {
        return !!signal && typeof signal.connect === "function";
    }

    function unlink(link) {
        try {
            link.signal.disconnect(link.fn);
        } catch (e) {
            // The window is already gone, and its connections with it.
        }
    }

    function windowId(w) {
        return String(w.internalId).replace(/[{}]/g, "");
    }

    function outputName(output) {
        return output && output.name ? String(output.name) : "";
    }

    function rect(g) {
        return {
            x: Math.round(g.x),
            y: Math.round(g.y),
            width: Math.round(g.width),
            height: Math.round(g.height)
        };
    }

    // --- Waddle's own penguin window and the outputs (Phase 1) ---------------------------

    function reportOwn(w) {
        try {
            if (!isOwnWindow(w) || String(w.caption) !== PENGUIN_TITLE || !w.frameGeometry) {
                return;
            }
            var payload = rect(w.frameGeometry);
            payload.title = PENGUIN_TITLE;
            payload.uuid = windowId(w);
            payload.output = outputName(w.output);
            var text = JSON.stringify(payload);
            if (lastSent[payload.uuid] === text) {
                return;
            }
            lastSent[payload.uuid] = text;
            send("OwnWindow", payload);
        } catch (e) {
            // A window that is going away can throw on property access; nothing to report.
        }
    }

    function consider(w) {
        try {
            // Only Waddle-class windows are watched; the title is checked on every report
            // because a caption can be set after the window is added.
            if (!w || String(w.resourceClass || "").toLowerCase() !== OWN_CLASS) {
                return;
            }
            var id = windowId(w);
            if (!watched[id]) {
                watched[id] = true;
                var onChange = function () {
                    reportOwn(w);
                };
                if (canConnect(w.frameGeometryChanged)) {
                    w.frameGeometryChanged.connect(onChange);
                }
                if (canConnect(w.outputChanged)) {
                    w.outputChanged.connect(onChange);
                }
                if (canConnect(w.captionChanged)) {
                    w.captionChanged.connect(onChange);
                }
            }
            reportOwn(w);
        } catch (e) {
            // See reportOwn.
        }
    }

    function forget(w) {
        try {
            var id = windowId(w);
            delete watched[id];
            delete lastSent[id];
        } catch (e) {
            // Nothing to forget.
        }
    }

    function reportOutputs() {
        try {
            var screens = workspace.screens || [];
            var outputs = [];
            for (var i = 0; i < screens.length; i++) {
                var entry = rect(screens[i].geometry);
                entry.name = outputName(screens[i]);
                outputs.push(entry);
            }
            var active = outputName(workspace.activeScreen);
            send("Outputs", { outputs: outputs, active: active === "" ? null : active });
        } catch (e) {
            // The host keeps its previous layout.
        }
    }

    // --- the target: the last activated window that is not Waddle's ----------------------

    // Spike S2.2 UNVERIFIED (scripting API): that Plasma 6.6 offers new QTimer() to scripts
    // with interval / singleShot / timeout / start / stop. Without it there is no throttle
    // and a change is sent whenever the payload differs from the last one sent.
    var throttle = null;
    try {
        if (typeof QTimer !== "undefined") {
            throttle = new QTimer();
            throttle.interval = THROTTLE_MS;
            throttle.singleShot = true;
            throttle.timeout.connect(onThrottle);
        }
    } catch (e) {
        throttle = null;
    }

    function startCooling(entry) {
        if (throttle) {
            entry.cooling = true;
            throttle.start();
        }
    }

    // Sends the target's state if it differs from the last payload sent for it.
    function sendTarget(entry) {
        var text;
        try {
            text = JSON.stringify(describeWindow(entry.w));
        } catch (e) {
            return false; // the window is going away
        }
        if (text === entry.lastText) {
            return false;
        }
        entry.lastText = text;
        callDBus(SERVICE, PATH, INTERFACE, "TargetChanged", text);
        return true;
    }

    function onTargetSignal(entry) {
        if (target !== entry) {
            return; // a late signal from a window that is no longer the target
        }
        if (entry.cooling) {
            entry.pending = true;
            return;
        }
        if (sendTarget(entry)) {
            startCooling(entry);
        }
    }

    function onThrottle() {
        var entry = target;
        if (!entry) {
            return;
        }
        entry.cooling = false;
        if (entry.pending) {
            entry.pending = false;
            onTargetSignal(entry);
        }
    }

    function clearTarget() {
        var entry = target;
        if (!entry) {
            return;
        }
        target = null;
        if (throttle) {
            try {
                throttle.stop();
            } catch (e) {
                // Nothing pending then.
            }
        }
        for (var i = 0; i < entry.links.length; i++) {
            unlink(entry.links[i]);
        }
        entry.links = [];
        for (var id in entry.popupLinks) {
            unlink(entry.popupLinks[id]);
        }
        entry.popupLinks = {};
    }

    function setTarget(w, id) {
        clearTarget();
        var entry = {
            w: w, id: id, links: [], lastText: "", cooling: false, pending: false,
            popupLinks: {}, popupsText: "[]"
        };
        var fn = function () {
            onTargetSignal(entry);
        };
        for (var i = 0; i < TARGET_SIGNALS.length; i++) {
            var signal = w[TARGET_SIGNALS[i]];
            if (canConnect(signal)) {
                signal.connect(fn);
                entry.links.push({ signal: signal, fn: fn });
            }
        }
        target = entry;
    }

    // --- the target's popups --------------------------------------------------------------

    // Spike S2.1 UNVERIFIED: which windows KWin shows to scripts as popups of another window
    // (menus, combo boxes, tooltips), and whether windowAdded / windowRemoved fire for them.
    // Kept conservative: a window counts only if it says it is a popup or a transient AND
    // its transientFor chain leads to the target. Anything else is not reported.
    function belongsToTarget(w, entry) {
        var parent = w;
        for (var depth = 0; depth < MAX_POPUP_DEPTH; depth++) {
            parent = parent.transientFor;
            if (!parent) {
                return false;
            }
            if (windowId(parent) === entry.id) {
                return true;
            }
        }
        return false;
    }

    function collectPopups(entry, excludeId) {
        var found = [];
        var windows = typeof workspace.windowList === "function" ? workspace.windowList() : [];
        for (var i = 0; i < windows.length && found.length < MAX_POPUPS; i++) {
            try {
                var w = windows[i];
                var id = windowId(w);
                if (id === entry.id || id === excludeId || isOwnClass(w)) {
                    continue;
                }
                if (w.popupWindow !== true && w.transient !== true) {
                    continue;
                }
                if (w.minimized === true || !w.frameGeometry || !belongsToTarget(w, entry)) {
                    continue;
                }
                found.push({ w: w, id: id });
            } catch (e) {
                // A window that is going away; skip it.
            }
        }
        return found;
    }

    // Recomputes the target's popups and reports the set when it changed. excludeId is a
    // window being removed, which KWin may still list.
    function refreshPopups(excludeId) {
        var entry = target;
        if (!entry) {
            return;
        }
        try {
            var found = collectPopups(entry, excludeId);
            var present = {};
            var popups = [];
            var i;
            for (i = 0; i < found.length; i++) {
                var g = payloadRect(found[i].w.frameGeometry);
                present[found[i].id] = true;
                popups.push({
                    uuid: found[i].id, x: g.x, y: g.y, width: g.width, height: g.height
                });
            }
            for (var id in entry.popupLinks) {
                if (!present[id]) {
                    unlink(entry.popupLinks[id]);
                    delete entry.popupLinks[id];
                }
            }
            for (i = 0; i < found.length; i++) {
                var signal = found[i].w.frameGeometryChanged;
                if (!entry.popupLinks[found[i].id] && canConnect(signal)) {
                    var fn = function () {
                        if (target === entry) {
                            refreshPopups();
                        }
                    };
                    signal.connect(fn);
                    entry.popupLinks[found[i].id] = { signal: signal, fn: fn };
                }
            }
            var text = JSON.stringify(popups);
            if (text !== entry.popupsText) {
                entry.popupsText = text;
                send("Popups", { target: entry.id, popups: popups });
            }
        } catch (e) {
            // The host keeps the previous set.
        }
    }

    // --- workspace events -----------------------------------------------------------------

    function onActivated(w) {
        try {
            if (!w) {
                return; // nothing is active; the host keeps its target
            }
            var info = describeWindow(w);
            var text = JSON.stringify(info);
            if (!info.own) {
                // One of Waddle's own windows never replaces the target: the host keeps
                // looking at the application the user was in.
                if (!target || target.id !== info.uuid) {
                    setTarget(w, info.uuid);
                }
                target.lastText = text;
                target.pending = false;
                startCooling(target);
            }
            callDBus(SERVICE, PATH, INTERFACE, "Activated", text);
            if (!info.own) {
                refreshPopups();
            }
        } catch (e) {
            // A window that is going away; the next activation is reported.
        }
    }

    function onWindowAdded(w) {
        consider(w);
        refreshPopups();
    }

    function onWindowRemoved(w) {
        forget(w);
        var id = null;
        try {
            id = windowId(w);
        } catch (e) {
            id = null;
        }
        if (target && id !== null && target.id === id) {
            clearTarget(); // nothing is sent: the next activation tells the host
            return;
        }
        refreshPopups(id === null ? undefined : id);
    }

    function onDesktopChanged() {
        send("DesktopChanged", {});
    }

    var apiOk = typeof workspace === "object" && workspace !== null &&
        typeof workspace.windowList === "function" && canConnect(workspace.windowAdded);
    send("Hello", { version: VERSION, apiOk: apiOk });
    if (typeof workspace !== "object" || workspace === null) {
        return;
    }

    reportOutputs();
    if (canConnect(workspace.screensChanged)) {
        workspace.screensChanged.connect(reportOutputs);
    }
    if (canConnect(workspace.windowAdded)) {
        workspace.windowAdded.connect(onWindowAdded);
    }
    if (canConnect(workspace.windowRemoved)) {
        workspace.windowRemoved.connect(onWindowRemoved);
    }
    if (typeof workspace.windowList === "function") {
        var windows = workspace.windowList();
        for (var i = 0; i < windows.length; i++) {
            consider(windows[i]);
        }
    }
    if (canConnect(workspace.windowActivated)) {
        workspace.windowActivated.connect(onActivated);
    }
    if (canConnect(workspace.currentDesktopChanged)) {
        workspace.currentDesktopChanged.connect(onDesktopChanged);
    }
    onActivated(workspace.activeWindow);
})();
